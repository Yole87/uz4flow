interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
}

export function EmojiPicker({ onSelect }: EmojiPickerProps) {
  const [activeTab, setActiveTab] = useState("smileys");

  return (
    <Tabs value={activeTab} onValueChange={setActiveTab} className="w-full">
      <TabsList className="w-full h-8 bg-muted/50 p-0.5 gap-0">
        {Object.entries(EMOJI_CATEGORIES).map(([key, { label }]) => (
          <TabsTrigger
            key={key}
            value={key}
            className="flex-1 h-7 px-0 text-base data-[state=active]:bg-background"
          >
            {label}
          </TabsTrigger>
        ))}
      </TabsList>
      {Object.entries(EMOJI_CATEGORIES).map(([key, { emojis }]) => (
        <TabsContent key={key} value={key} className="mt-1">
          <ScrollArea className="h-48">
            <div className="grid grid-cols-8 gap-0.5">
              {emojis.map((emoji, i) => (
                <button
                  key={`${emoji}-${i}`}
                  type="button"
                  onClick={() => onSelect(emoji)}
                  className="h-8 w-8 flex items-center justify-center text-lg hover:bg-muted rounded cursor-pointer transition-colors"
                >
                  {emoji}
                </button>
              ))}
            </div>
          </ScrollArea>
        </TabsContent>
      ))}
    </Tabs>
  );
}
